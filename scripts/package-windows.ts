import { cpSync, copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve, join, dirname } from 'node:path';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { originUrl } from '../src/shared/security.js';
const origin = originUrl(process.env.RELAY_URL ?? 'http://127.0.0.1:8790');
if (process.platform !== 'win32') throw new Error('Build the native helper on Windows.');
if (!existsSync('dist/agent.mjs')) throw new Error('Run npm run build and npm run native first.');
const pkg = JSON.parse(readFileSync('package.json', 'utf8'));
for (const [command, args] of [[resolve('release/RemoteCompanion.exe'), ['--version']], [process.execPath, ['dist/agent.mjs', '--version']]] as const) {
  if (execFileSync(command, args, { encoding: 'utf8', windowsHide: true }).trim() !== pkg.version) throw new Error('Helper build version mismatch. Rebuild both the agent and native executable.');
}
const publicPackage = origin.startsWith('https:');
const output = resolve('release', publicPackage ? 'windows-public' : 'windows'); mkdirSync(output, { recursive: true });
copyFileSync(process.execPath, join(output, 'node.exe'));
copyFileSync('release/RemoteCompanion.exe', join(output, 'RemoteCompanion.exe'));
copyFileSync('release/companion.ico', join(output, 'companion.ico'));
cpSync('release/icons', join(output, 'icons'), { recursive: true });
cpSync('dist', join(output, 'dist'), { recursive: true });
writeFileSync(join(output, 'package.json'), JSON.stringify({ name: pkg.name, version: pkg.version, license: pkg.license, private: true, type: 'module', dependencies: pkg.dependencies, overrides: pkg.overrides }, null, 2));
copyFileSync('package-lock.json', join(output, 'package-lock.json'));
for (const file of ['LICENSE', 'NOTICE', 'THIRD_PARTY_NOTICES.md']) copyFileSync(file, join(output, file));
writeFileSync(join(output, 'relay.json'), JSON.stringify({ origin }, null, 2));
copyFileSync('doc/windows-installer-and-power.md', join(output, 'INSTALLER.md'));
copyFileSync('doc/remembered-login.md', join(output, 'REMEMBERED-LOGIN.md'));
copyFileSync('doc/desktop-compatibility.md', join(output, 'COMPATIBILITY.md'));
copyFileSync('doc/plan-mode.md', join(output, 'PLAN-MODE.md'));
copyFileSync('doc/queued-send-and-steering.md', join(output, 'QUEUED-SEND.md'));
const license = join(dirname(process.execPath), 'LICENSE'); if (existsSync(license)) copyFileSync(license, join(output, 'NODE-LICENSE.txt'));
const npmCli = process.env.npm_execpath ?? join(dirname(process.execPath), 'node_modules/npm/bin/npm-cli.js');
execFileSync(process.execPath, [npmCli, 'ci', '--omit=dev', '--ignore-scripts', '--registry=https://registry.npmjs.org'], { cwd: output, stdio: 'inherit', windowsHide: true });
const archiveName = publicPackage ? 'codex-mobile-windows-public.zip' : 'codex-mobile-windows.zip';
const archive = resolve('release', archiveName);
const distributable = ['node.exe', 'RemoteCompanion.exe', 'companion.ico', 'icons', 'dist', 'node_modules', 'package.json', 'package-lock.json', 'relay.json', 'LICENSE', 'NOTICE', 'THIRD_PARTY_NOTICES.md', 'NODE-LICENSE.txt', 'INSTALLER.md', 'REMEMBERED-LOGIN.md', 'COMPATIBILITY.md', 'PLAN-MODE.md', 'QUEUED-SEND.md'];
for (const file of distributable) if (!existsSync(join(output, file))) throw new Error(`Missing distributable: ${file}`);
execFileSync('tar.exe', ['-a', '-c', '-f', archive, '-C', output, ...distributable], { windowsHide: true });
const digest = createHash('sha256').update(readFileSync(archive)).digest('hex');
writeFileSync(archive + '.sha256', digest + '  ' + archiveName + '\n');
console.log(JSON.stringify({ archive, sha256: digest, origin, signed: false }, null, 2));
